class Command(BaseCommand):
    help = "Seed DailyPage data from the devotional PDF (Jan 1 to Mar 31)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete existing DailyPage and ReadingLink data before seeding",
        )
        parser.add_argument(
            "--year",
            type=int,
            default=date.today().year,
            help="Year to seed into the database (default: current year)",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        year = options["year"]

        if options["clear"]:
            ReadingLink.objects.all().delete()
            DailyPage.objects.all().delete()

        for plan in DEVOTIONS:
            page_date = date(year, plan["month"], plan["day"])

            clean_body = remove_pdf_spacing(plan["body"])
            clean_prayer = remove_pdf_spacing(plan["prayer"])

            page, created = DailyPage.objects.get_or_create(
                page_date=page_date,
                defaults={
                    "title": f'{plan["month"]} 月 {plan["day"]} 日：{plan["title"]}',
                    "body": clean_body,
                    "prayer": clean_prayer,
                    "image_path": DEFAULT_IMAGE,
                },
            )

            if not created:
                page.title = f'{plan["month"]} 月 {plan["day"]} 日：{plan["title"]}'
                page.body = clean_body
                page.prayer = clean_prayer
                page.image_path = DEFAULT_IMAGE
                page.save()

            page.reading_links.all().delete()

            for order, (ref_text, url) in enumerate(plan["links"], start=1):
                ReadingLink.objects.create(
                    page=page,
                    ref_text=ref_text,
                    url=url,
                    display_order=order,
                )

        self.stdout.write(
            self.style.SUCCESS(
                f"Seeded {len(DEVOTIONS)} devotional pages for year {year} successfully."
            )
        )